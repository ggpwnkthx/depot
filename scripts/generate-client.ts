#!/usr/bin/env bun
/**
 * The types of the client of a deployment.
 *
 * The client of the API is generic: it speaks the contract of v1 and it
 * knows nothing of the collections of a deployment. A deployment that
 * wants the types of its own collections generates them with this
 * command, and it hands them to the client:
 *
 *   const client = new DataClient<Collections>({ baseUrl, workspaceId })
 *   const page = await client.list('articles')   // the rows of the articles
 *
 * The command:
 *
 *   bun run scripts/generate-client.ts            # writes the file
 *   bun run scripts/generate-client.ts --check    # refuses a stale file
 *
 * The file it writes is `packages/client/src/deployment.ts`. It is the
 * artifact of the deployment of this repository: another deployment
 * writes its own file, with the same shape, in its own repository.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { parseManifestBundle, type FieldDefinition, type FieldType } from '../src/domains/schema'

/** The file that the command writes. */
const TARGET = 'packages/client/src/deployment.ts'

/** The manifest of the deployment. */
const MANIFEST = 'manifests/schema.json'

/**
 * The type of a field, in the language of the client.
 *
 * A decimal is a string: the service keeps the exactness of a decimal
 * and a double does not. A timestamp is a string: the service writes
 * the timestamps in UTC with the resolution of a millisecond. A json
 * field is unknown: the shape of a json value belongs to the
 * deployment that wrote it.
 */
function typeOf(definition: FieldDefinition): string {
  const types: Record<FieldType, string> = {
    string: 'string',
    text: 'string',
    enum: 'string',
    boolean: 'boolean',
    integer: 'number',
    decimal: 'string',
    uuid: 'string',
    timestamp: 'string',
    json: 'unknown',
  }
  return types[definition.type]
}

/** The name of the type of a collection. */
function typeName(key: string): string {
  return `${key
    .split('_')
    .filter((part) => part.length > 0)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('')}Record`
}

/** The name of a field of a record. */
function fieldName(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check')
  const manifest = parseManifestBundle(await readFile(MANIFEST, 'utf8'))
  const lines: string[] = []
  lines.push('// The types of the collections of the deployment.')
  lines.push('//')
  lines.push('// This file is generated by `bun run scripts/generate-client.ts`.')
  lines.push('// It is the artifact of the deployment of this repository: a')
  lines.push('// deployment of another repository writes its own file, with the')
  lines.push('// same shape.')
  lines.push('')
  lines.push('/* eslint-disable */')
  lines.push('')

  for (const collection of manifest.collections) {
    const name = typeName(collection.key)
    lines.push(`/** The row of the collection "${collection.key}". */`)
    lines.push(`export interface ${name} {`)
    lines.push('  id: string')
    lines.push('  version: number')
    for (const [field, definition] of Object.entries(collection.fields)) {
      const nullable = definition.nullable ? ' | null' : ''
      const optional = definition.required ? '' : '?'
      lines.push(`  ${fieldName(field)}${optional}: ${typeOf(definition)}${nullable}`)
    }
    lines.push('}')
    lines.push('')
  }

  lines.push('/** The collections of the deployment. */')
  // The map is a type and not an interface: a type has the implicit
  // index signature that the client reads as the constraint of its map.
  lines.push('export type Collections = {')
  for (const collection of manifest.collections) {
    lines.push(`  ${fieldName(collection.key)}: ${typeName(collection.key)}`)
  }
  lines.push('}')
  lines.push('')

  const content = lines.join('\n')
  if (check) {
    const current = await readFile(TARGET, 'utf8').catch(() => '')
    if (current !== content) {
      console.error(`the file "${TARGET}" is not the one of the manifest: run the command`)
      process.exitCode = 1
      return
    }
    console.log(`the file "${TARGET}" is the one of the manifest`)
    return
  }
  await writeFile(TARGET, content)
  console.log(`the file "${TARGET}" holds the types of ${manifest.collections.length} collections`)
}

await main()
